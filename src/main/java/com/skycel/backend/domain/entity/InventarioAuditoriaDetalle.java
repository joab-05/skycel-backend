package com.skycel.backend.domain.entity;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.envers.Audited;
import org.hibernate.envers.RelationTargetAuditMode;

@Entity
@Audited
@Table(name = "inventario_auditoria_detalle")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class InventarioAuditoriaDetalle {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "iddetalle_inv")
    private Integer iddetalleInv;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "idinventario", nullable = false)
    private InventarioAuditoria inventarioAuditoria;

    @Audited(targetAuditMode = RelationTargetAuditMode.NOT_AUDITED)
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "idseccion")
    private Seccion seccion;   // vacía en un artículo de equipos: esos se cuentan por IMEI, no por sección

    /** El artículo, solo cuando son equipos (celulares o tablets): ahí {@code codpro} es un identificador interno «EQ…». */
    @Audited(targetAuditMode = RelationTargetAuditMode.NOT_AUDITED)
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "idprodmaster")
    private ProductoMaster productoMaster;

    /** Por qué se justificó la diferencia en vez de ajustar las existencias. */
    @Column(name = "motivo", length = 255)
    private String motivo;

    /** Lo que contó el encargado, si el administrador lo corrigió al revisar (queda en blanco si nadie lo tocó). */
    @Column(name = "conteo_original")
    private Short conteoOriginal;

    /** Por qué y quién corrigió el conteo en la revisión. */
    @Column(name = "correccion_motivo", length = 255)
    private String correccionMotivo;

    @Column(name = "correccion_por", length = 60)
    private String correccionPor;

    @Column(name = "codpro", nullable = false, length = 25)
    private String codpro;

    @Column(name = "conteo", nullable = false, columnDefinition = "SMALLINT DEFAULT 1")
    private Short conteo;

    @Column(name = "stock_sistema", columnDefinition = "SMALLINT DEFAULT 0")
    private Short stockSistema;

    // "diferencia" is generated by the database entirely, so we set insertable/updatable to false
    @Column(name = "diferencia", insertable = false, updatable = false)
    private Integer diferencia;

    @Column(name = "estado", nullable = false, columnDefinition = "TINYINT")
    private Byte estado;
}
